#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""429-wait legacy shim for agents using exit-code/stderr recovery.

Current Claude Code installations use StopFailure hooks instead; interactive
Claude sessions can remain open after a final 429. This shim remains for other
agents and older manual installations.

Usage (generated by install scripts, not typed by users):
  python 429-wait-shim.py --adapter codex --shim-dir ~/.local/bin -- <args>
"""
import argparse
import json
import os
import re
import signal
import subprocess
import sys
import threading
import time
import urllib.error
import urllib.request

# ---------------------------------------------------------------------------
# TOML parser — tomllib (3.11+) with minimal fallback for 3.8-3.10
# ---------------------------------------------------------------------------
try:
    import tomllib
except ModuleNotFoundError:
    tomllib = None


def _toml_fallback_parse(text):
    """Minimal TOML parser: supports strings, ints, floats, bools, arrays,
    inline tables, and [section] / [section.sub] headers. Enough for our
    adapter configs. Not a full TOML implementation."""
    root = {}
    current = root
    current_path = []

    def set_nested(d, keys, val):
        for k in keys[:-1]:
            d = d.setdefault(k, {})
        d[keys[-1]] = val

    def get_or_create(d, keys):
        for k in keys:
            d = d.setdefault(k, {})
        return d

    def parse_value(v):
        v = v.strip()
        if not v:
            raise ValueError("empty value")
        if v == "true":
            return True
        if v == "false":
            return False
        if v.startswith('"') and v.endswith('"'):
            return v[1:-1].replace('\\n', '\n').replace('\\t', '\t').replace('\\\\', '\\')
        if v.startswith("'") and v.endswith("'"):
            return v[1:-1]
        if v.startswith("["):
            return parse_array(v)
        if v.startswith("{"):
            return parse_inline_table(v)
        try:
            return int(v)
        except ValueError:
            pass
        try:
            return float(v)
        except ValueError:
            pass
        return v

    def parse_array(s):
        s = s.strip()
        if not (s.startswith("[") and s.endswith("]")):
            raise ValueError("bad array: %s" % s)
        inner = s[1:-1].strip()
        if not inner:
            return []
        items = []
        buf = ""
        depth = 0
        in_str = False
        str_ch = None
        for ch in inner:
            if in_str:
                buf += ch
                if ch == str_ch:
                    in_str = False
                continue
            if ch in ('"', "'"):
                in_str = True
                str_ch = ch
                buf += ch
                continue
            if ch in ("[", "{"):
                depth += 1
            elif ch in ("]", "}"):
                depth -= 1
            if ch == "," and depth == 0:
                b = buf.strip()
                if b:
                    items.append(parse_value(b))
                buf = ""
            else:
                buf += ch
        b = buf.strip()
        if b:
            items.append(parse_value(b))
        return items

    def parse_inline_table(s):
        s = s.strip()
        if not (s.startswith("{") and s.endswith("}")):
            raise ValueError("bad inline table: %s" % s)
        inner = s[1:-1].strip()
        if not inner:
            return {}
        result = {}
        for part in split_top_level(inner, ","):
            part = part.strip()
            if not part:
                continue
            eq = part.index("=")
            k = part[:eq].strip().strip('"').strip("'")
            v = parse_value(part[eq + 1:])
            result[k] = v
        return result

    def split_top_level(s, sep):
        parts = []
        buf = ""
        depth = 0
        in_str = False
        str_ch = None
        for ch in s:
            if in_str:
                buf += ch
                if ch == str_ch:
                    in_str = False
                continue
            if ch in ('"', "'"):
                in_str = True
                str_ch = ch
                buf += ch
                continue
            if ch in ("[", "{"):
                depth += 1
            elif ch in ("]", "}"):
                depth -= 1
            if ch == sep and depth == 0:
                parts.append(buf)
                buf = ""
            else:
                buf += ch
        parts.append(buf)
        return parts

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("["):
            header = line.strip("[]").strip()
            current_path = header.split(".")
            current = get_or_create(root, current_path)
            continue
        if "=" not in line:
            continue
        eq = line.index("=")
        key = line[:eq].strip()
        val_str = line[eq + 1:].split("#")[0].strip() if "#" in line[eq + 1:] else line[eq + 1:].strip()
        # handle comment inside strings — crude but good enough
        raw_val = line[eq + 1:].strip()
        if raw_val.startswith('"') or raw_val.startswith("'") or raw_val.startswith("[") or raw_val.startswith("{"):
            val_str = raw_val
        current[key] = parse_value(val_str)

    return root


def load_toml(path):
    with open(path, "rb" if tomllib else "r", encoding=None if tomllib else "utf-8") as f:
        if tomllib:
            return tomllib.load(f)
        return _toml_fallback_parse(f.read())


# ---------------------------------------------------------------------------
# Adapter loading
# ---------------------------------------------------------------------------
def find_adapter(name):
    """Search for adapter TOML: beside the script, then ~/.local/share/429-wait/adapters/."""
    script_dir = os.path.dirname(os.path.abspath(__file__))
    candidates = [
        os.path.join(script_dir, "..", "adapters", name + ".toml"),
        os.path.join(os.path.expanduser("~"), ".local", "share", "429-wait", "adapters", name + ".toml"),
    ]
    for p in candidates:
        p = os.path.normpath(p)
        if os.path.isfile(p):
            return load_toml(p)
    sys.exit("429-wait: adapter '%s' not found. Searched:\n  %s" % (name, "\n  ".join(candidates)))


# ---------------------------------------------------------------------------
# Real binary discovery
# ---------------------------------------------------------------------------
def find_real_binary(command, shim_dir):
    """Find the real binary for `command` in PATH, skipping shim_dir."""
    shim_dir = os.path.normcase(os.path.abspath(shim_dir)) if shim_dir else ""
    path_dirs = os.environ.get("PATH", "").split(os.pathsep)
    extensions = [""]  # Unix
    if os.name == "nt":
        extensions = [".CMD", ".cmd", ".EXE", ".exe", ".BAT", ".bat", ".COM", ".com", ".PS1", ".ps1", ""]

    for d in path_dirs:
        d_norm = os.path.normcase(os.path.abspath(d))
        if shim_dir and d_norm == shim_dir:
            continue
        for ext in extensions:
            candidate = os.path.join(d, command + ext)
            if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
                # self-detection guard: don't return ourself
                try:
                    with open(candidate, "r", errors="ignore") as f:
                        head = f.read(512)
                    if "429-wait-shim" in head:
                        continue
                except (OSError, UnicodeDecodeError):
                    pass
                return candidate
    return None


# ---------------------------------------------------------------------------
# Credential reading
# ---------------------------------------------------------------------------
def read_credential(key_spec, settings_data=None):
    """Read a credential from env var or settings JSON.
    key_spec like 'env.ANTHROPIC_API_KEY' reads os.environ['ANTHROPIC_API_KEY'].
    key_spec like 'settings.env.ANTHROPIC_API_KEY' dot-navigates the JSON.
    """
    if key_spec.startswith("env."):
        env_name = key_spec[4:]
        val = os.environ.get(env_name, "")
        if val:
            return val
        # also try settings file
        if settings_data:
            env_block = settings_data.get("env", {})
            return env_block.get(env_name, "")
        return ""
    if settings_data and key_spec.startswith("settings."):
        parts = key_spec[9:].split(".")
        node = settings_data
        for p in parts:
            if isinstance(node, dict):
                node = node.get(p, "")
            else:
                return ""
        return node if isinstance(node, str) else ""
    return os.environ.get(key_spec, "")


def load_settings(path):
    """Load a JSON settings file, return dict or {} on failure."""
    path = os.path.expanduser(path)
    if not os.path.isfile(path):
        return {}
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}


# ---------------------------------------------------------------------------
# Generalized probe
# ---------------------------------------------------------------------------
def probe(endpoint, api_key, model, adapter_cfg):
    """Probe an LLM API endpoint. Returns ('ok'|'limited'|'error', detail)."""
    probe_cfg = adapter_cfg.get("probe", {})
    params = probe_cfg.get("params", {})
    max_tokens = params.get("max_tokens", 64)
    timeout = params.get("timeout", 25)
    limited_codes = set(params.get("limited_status_codes", [429, 401, 403]))

    body_format = probe_cfg.get("body", {}).get("format", "anthropic")
    if body_format == "openai":
        body = json.dumps({
            "model": model,
            "max_tokens": max_tokens,
            "messages": [{"role": "user", "content": "hi"}],
        }).encode()
    else:  # anthropic
        body = json.dumps({
            "model": model,
            "max_tokens": max_tokens,
            "messages": [{"role": "user", "content": "hi"}],
        }).encode()

    headers = {"Content-Type": "application/json"}
    auth_header = probe_cfg.get("auth_header", "x-api-key")
    auth_prefix = probe_cfg.get("auth_prefix", "")
    headers[auth_header] = auth_prefix + api_key

    # extra headers (e.g. anthropic-version)
    for k, v in probe_cfg.get("extra_headers", {}).items():
        headers[k] = v

    # Anthropic also accepts Authorization: Bearer
    if body_format == "anthropic":
        headers.setdefault("Authorization", "Bearer " + api_key)

    # Many relays / Cloudflare Workers block the default python-urllib UA
    headers.setdefault("User-Agent", "429-wait/1.0")

    endpoint_path = probe_cfg.get("endpoint_path", "/v1/messages")
    url = endpoint.rstrip("/") + endpoint_path

    req = urllib.request.Request(url, data=body, headers=headers)
    try:
        r = urllib.request.urlopen(req, timeout=timeout)
        r.read()
        return "ok", "HTTP %d" % r.status
    except urllib.error.HTTPError as e:
        txt = e.read().decode("utf-8", "ignore")
        if e.code in limited_codes:
            return "limited", "%d %s" % (e.code, txt[:160])
        return "error", "HTTP %d %s" % (e.code, txt[:160])
    except Exception as e:
        return "error", "%s: %s" % (type(e).__name__, str(e)[:120])


# ---------------------------------------------------------------------------
# Stderr tee thread
# ---------------------------------------------------------------------------
class StderrCapture:
    """Read subprocess stderr, write to real stderr in real time, accumulate."""

    def __init__(self, pipe):
        self.pipe = pipe
        self.lines = []
        self.thread = threading.Thread(target=self._run, daemon=True)

    def start(self):
        self.thread.start()

    def _run(self):
        try:
            for raw in self.pipe:
                line = raw.decode("utf-8", "replace")
                sys.stderr.write(line)
                sys.stderr.flush()
                self.lines.append(line)
        except Exception:
            pass

    def join(self, timeout=5):
        self.thread.join(timeout=timeout)

    def text(self):
        return "".join(self.lines)


# ---------------------------------------------------------------------------
# Rate limit detection
# ---------------------------------------------------------------------------
def detect_rate_limit(exit_code, stderr_text, adapter_cfg):
    """Check if the agent exited due to a rate limit."""
    det = adapter_cfg.get("detection", {})
    expected_codes = det.get("exit_codes", [1])
    require_match = det.get("require_stderr_match", True)
    patterns = det.get("stderr_patterns", [])

    if exit_code not in expected_codes:
        return False

    if not require_match:
        return True

    for pat in patterns:
        if re.search(pat, stderr_text, re.IGNORECASE):
            return True
    return False


# ---------------------------------------------------------------------------
# Probe loop
# ---------------------------------------------------------------------------
def run_probe_loop(endpoint, api_key, model, adapter_cfg, state_dir, tag):
    """Probe until recovery or give up. Returns True if recovered."""
    params = adapter_cfg.get("probe", {}).get("params", {})
    interval = params.get("interval", 300)
    max_attempts = params.get("max_attempts", 120)

    os.makedirs(state_dir, exist_ok=True)
    log_path = os.path.join(state_dir, "shim-%s.log" % tag)
    pid_path = os.path.join(state_dir, "shim-%s.pid" % tag)

    def log(msg):
        line = "%s [shim:%s] %s" % (time.strftime("%Y-%m-%d %H:%M:%S"), tag, msg)
        try:
            with open(log_path, "a", encoding="utf-8") as f:
                f.write(line + "\n")
        except OSError:
            pass
        print(line, file=sys.stderr, flush=True)

    # single instance guard
    if os.path.isfile(pid_path):
        try:
            old_pid = int(open(pid_path).read().strip())
            os.kill(old_pid, 0)
            log("another shim probe already running (pid %d), attaching" % old_pid)
            # wait for the other one
            while os.path.isfile(pid_path):
                time.sleep(10)
            return True  # assume the other instance recovered
        except (OSError, ValueError):
            pass  # stale pid file

    with open(pid_path, "w") as f:
        f.write(str(os.getpid()))

    log("START probe loop: interval=%ds max=%d endpoint=%s" % (interval, max_attempts, endpoint))

    try:
        for attempt in range(1, max_attempts + 1):
            status, detail = probe(endpoint, api_key, model, adapter_cfg)
            if status == "ok":
                log("RECOVERED at attempt %d/%d: %s" % (attempt, max_attempts, detail))
                return True
            elif status == "limited":
                log("attempt %d/%d: STILL LIMITED :: %s" % (attempt, max_attempts, detail))
            else:
                log("attempt %d/%d: ERROR :: %s" % (attempt, max_attempts, detail))
            time.sleep(interval)
        log("GIVE UP after %d attempts" % max_attempts)
        return False
    finally:
        try:
            os.remove(pid_path)
        except OSError:
            pass


# ---------------------------------------------------------------------------
# Recovery command
# ---------------------------------------------------------------------------
def build_recovery_command(original_args, real_binary, adapter_cfg):
    """Build the command to re-launch the agent after recovery."""
    rec = adapter_cfg.get("recovery", {})
    strategy = rec.get("strategy", "replay")

    if strategy == "continue":
        template = rec.get("command_template", "{command} --continue")
        cmd = template.replace("{command}", real_binary)
        return cmd.split()
    else:  # replay
        return [real_binary] + list(original_args)


# ---------------------------------------------------------------------------
# Banner
# ---------------------------------------------------------------------------
def print_banner(agent_name):
    print("\n" + "=" * 60, file=sys.stderr)
    print("  429-wait: %s hit a rate limit" % agent_name, file=sys.stderr)
    print("  Probing API until quota restores...", file=sys.stderr)
    print("  (Ctrl+C to abort)", file=sys.stderr)
    print("=" * 60 + "\n", file=sys.stderr)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(
        description="429-wait shim: transparent rate-limit recovery for CLI agents.",
        usage="429-wait-shim.py --adapter NAME [--shim-dir DIR] -- <agent args>",
    )
    ap.add_argument("--adapter", required=True, help="adapter name (e.g. claude-code)")
    ap.add_argument("--shim-dir", default="", help="directory containing the shim scripts (excluded from PATH search)")
    ap.add_argument("--state-dir", default=os.path.expanduser(os.path.join("~", ".429-wait")),
                    help="directory for logs and pid files")
    ap.add_argument("--max-retries", type=int, default=5,
                    help="max consecutive rate-limit recovery cycles")
    ap.add_argument("agent_args", nargs=argparse.REMAINDER, help="arguments for the real agent")
    args = ap.parse_args()

    # strip leading '--' from agent_args
    agent_args = args.agent_args
    if agent_args and agent_args[0] == "--":
        agent_args = agent_args[1:]

    # load adapter
    adapter_cfg = find_adapter(args.adapter)
    agent = adapter_cfg.get("agent", {})
    command = agent.get("command", args.adapter)
    agent_name = agent.get("name", args.adapter)

    # find real binary
    real_binary = find_real_binary(command, args.shim_dir)
    if not real_binary:
        sys.exit("429-wait: cannot find real '%s' in PATH (shim_dir=%s excluded)" % (command, args.shim_dir))

    # resolve credentials for probing (lazy — only needed if rate limit detected)
    def get_probe_credentials():
        probe_cfg = adapter_cfg.get("probe", {})
        sk = probe_cfg.get("settings_keys", {})
        settings_path = probe_cfg.get("settings_file", "")
        settings_data = load_settings(settings_path) if settings_path else {}
        defaults = probe_cfg.get("defaults", {})

        base_url = read_credential(sk.get("base_url", ""), settings_data) or defaults.get("base_url", "")
        api_key = read_credential(sk.get("api_key", ""), settings_data)
        model = read_credential(sk.get("model", ""), settings_data) or defaults.get("model", "")
        return base_url.rstrip("/"), api_key, model

    # main loop
    retries = 0
    current_cmd = [real_binary] + agent_args
    tag = agent_name

    while True:
        # run the agent
        try:
            proc = subprocess.Popen(
                current_cmd,
                stdin=sys.stdin,
                stdout=sys.stdout,  # pass through untouched (TUI safe)
                stderr=subprocess.PIPE,
            )
        except FileNotFoundError:
            sys.exit("429-wait: cannot execute '%s'" % current_cmd[0])

        cap = StderrCapture(proc.stderr)
        cap.start()

        # forward signals to child
        def forward_signal(signum, _frame):
            try:
                proc.send_signal(signum)
            except OSError:
                pass

        if os.name != "nt":
            for sig in (signal.SIGINT, signal.SIGTERM):
                signal.signal(sig, forward_signal)

        proc.wait()
        cap.join()
        exit_code = proc.returncode
        stderr_text = cap.text()

        # check for rate limit
        if not detect_rate_limit(exit_code, stderr_text, adapter_cfg):
            sys.exit(exit_code)

        retries += 1
        if retries > args.max_retries:
            print("429-wait: max retries (%d) reached, giving up." % args.max_retries, file=sys.stderr)
            sys.exit(exit_code)

        # rate limit detected — probe and recover
        print_banner(agent_name)

        base_url, api_key, model = get_probe_credentials()
        if not base_url or not api_key:
            print("429-wait: cannot probe (missing credentials). Exiting with agent's exit code.",
                  file=sys.stderr)
            sys.exit(exit_code)

        recovered = run_probe_loop(base_url, api_key, model, adapter_cfg, args.state_dir, tag)
        if not recovered:
            sys.exit(2)

        # build recovery command
        current_cmd = build_recovery_command(agent_args, real_binary, adapter_cfg)
        print("\n429-wait: quota restored! Re-launching: %s\n" % " ".join(current_cmd), file=sys.stderr)


if __name__ == "__main__":
    sys.exit(main())
