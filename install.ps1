<#
.SYNOPSIS
  Installs 429-wait globally. Claude Code uses StopFailure hooks; other
  supported agents keep the transparent command shim.
.PARAMETER Agents
  Agents to enable. Defaults to all supported agents.
#>
param(
  [string[]]$Agents = @('claude', 'codex', 'aider')
)

$ErrorActionPreference = 'Stop'
$src  = $PSScriptRoot
$dest = Join-Path $env:USERPROFILE '.local\bin'
$adapterDest = Join-Path $env:USERPROFILE '.local\share\429-wait\adapters'
$stateDir = Join-Path $env:USERPROFILE '.429-wait'
$null = New-Item -ItemType Directory -Force -Path $dest, $adapterDest, $stateDir

# Core shim, hook entry, settings helper, and standalone daemon.
foreach ($name in '429-wait-shim.py', '429-wait.py', '429-wait-hook.py', '429-wait-settings.py', '429-wait-terminal.py') {
  Copy-Item (Join-Path $src "bin\$name") -Destination $dest -Force
}
Copy-Item (Join-Path $src 'adapters\*.toml') -Destination $adapterDest -Force
Set-Content -Path (Join-Path $dest '429-wait-py.cmd') -Encoding ASCII -Value (
  "@echo off`r`npython `"%USERPROFILE%\.local\bin\429-wait.py`" %*"
)

# Legacy commands remain available for manual use.
foreach ($name in '429-wait.ps1', '429-wait-watch.ps1') {
  Copy-Item (Join-Path $src "bin\$name") -Destination $dest -Force
  $cmd = $name -replace '\.ps1$', '.cmd'
  Set-Content -Path (Join-Path $dest $cmd) -Encoding ASCII -Value (
    "@echo off`r`npwsh -NoProfile -ExecutionPolicy Bypass -File `"%USERPROFILE%\.local\bin\$name`" %*"
  )
}
Copy-Item (Join-Path $src 'bin\429-wait.sh') -Destination $dest -Force

$adapterNames = @{
  claude = 'claude-code'
  codex = 'codex'
  aider = 'aider'
}
$shimsCreated = @()
$hookInstalled = $false

foreach ($command in $Agents) {
  if (-not $adapterNames.ContainsKey($command)) {
    throw "Unsupported agent: $command"
  }

  $realBinary = Get-Command $command -All -ErrorAction SilentlyContinue |
    Where-Object {
      $_.Source -and -not $_.Source.StartsWith($dest, [System.StringComparison]::OrdinalIgnoreCase)
    } |
    Select-Object -First 1
  if (-not $realBinary) {
    Write-Output "  skip $command (not found in PATH)"
    continue
  }

  if ($command -eq 'claude') {
    # Replace only wrappers previously generated by 429-wait.
    foreach ($extension in '.cmd', '.ps1') {
      $oldShim = Join-Path $dest "claude$extension"
      if ((Test-Path $oldShim) -and ((Get-Content $oldShim -Raw) -match '429-wait-(shim|terminal)\.py')) {
        Remove-Item $oldShim -Force
        Write-Output "  replaced previous Claude wrapper: $oldShim"
      }
    }
    & python -I (Join-Path $dest '429-wait-settings.py') install --hook-script (Join-Path $dest '429-wait-hook.py')
    if ($LASTEXITCODE -ne 0) {
      throw 'Failed to install the Claude Code StopFailure hook'
    }
    Set-Content -Path (Join-Path $dest 'claude.cmd') -Encoding ASCII -Value (
      "@echo off`r`npython `"%USERPROFILE%\.local\bin\429-wait-terminal.py`" --shim-dir `"%USERPROFILE%\.local\bin`" -- %*"
    )
    Set-Content -Path (Join-Path $dest 'claude.ps1') -Encoding UTF8 -Value (
      "& python `"`$env:USERPROFILE\.local\bin\429-wait-terminal.py`" --shim-dir `"`$env:USERPROFILE\.local\bin`" -- @args`r`nexit `$LASTEXITCODE"
    )
    $shimsCreated += 'claude'
    $hookInstalled = $true
    Write-Output "  supervisor + hook: Claude Code -> same-window, same-session recovery"
    continue
  }

  $adapter = $adapterNames[$command]
  Set-Content -Path (Join-Path $dest "$command.cmd") -Encoding ASCII -Value (
    "@echo off`r`npython `"%USERPROFILE%\.local\bin\429-wait-shim.py`" --adapter $adapter --shim-dir `"%USERPROFILE%\.local\bin`" -- %*"
  )
  Set-Content -Path (Join-Path $dest "$command.ps1") -Encoding UTF8 -Value (
    "& python `"`$env:USERPROFILE\.local\bin\429-wait-shim.py`" --adapter $adapter --shim-dir `"`$env:USERPROFILE\.local\bin`" -- @args`r`nexit `$LASTEXITCODE"
  )
  $shimsCreated += $command
  Write-Output "  shim: $command -> $($realBinary.Source)"
}

$configDir = if ($env:CLAUDE_CONFIG_DIR) { $env:CLAUDE_CONFIG_DIR } else { Join-Path $env:USERPROFILE '.claude' }
$manifest = [ordered]@{
  installed_at = [DateTime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ')
  dest = $dest
  adapter_dest = $adapterDest
  shims = $shimsCreated
  hook_installed = $hookInstalled
  settings_file = (Join-Path $configDir 'settings.json')
  files = @('429-wait-shim.py', '429-wait.py', '429-wait-hook.py', '429-wait-settings.py', '429-wait-terminal.py')
}
$manifest | ConvertTo-Json | Set-Content -Path (Join-Path $stateDir 'manifest.json') -Encoding UTF8

if (($env:PATH -split ';') -notcontains $dest) {
  Write-Output ''
  Write-Output "WARNING: $dest is not in PATH. It must precede other agent shim directories."
}

Write-Output ''
Write-Output "Installed to $dest"
Write-Output "  Claude Code StopFailure hook: $hookInstalled"
Write-Output "  supervised commands: $($shimsCreated -join ', ')"
Write-Output '  standalone daemon: 429-wait-py.cmd'
Write-Output '  legacy commands: 429-wait.cmd, 429-wait-watch.cmd, 429-wait.sh'
Write-Output "Uninstall: pwsh $src\uninstall.ps1"
